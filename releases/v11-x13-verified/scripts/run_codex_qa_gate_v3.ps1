param(
    [Parameter(Mandatory=$true)][string]$FilePath,
    [string]$UserRequest = "",
    [ValidateSet("low","medium","high")][string]$Reasoning = "medium"
)

$ErrorActionPreference = "Stop"

if (!(Test-Path -LiteralPath $FilePath -PathType Leaf)) { throw "검수할 파일을 찾을 수 없습니다: $FilePath" }

$ext = [System.IO.Path]::GetExtension($FilePath).ToLowerInvariant()
if ($ext -notin @(".pptx", ".ppt")) { throw "QA Gate v3는 우선 PPT/PPTX 전용입니다." }

$codexPath = "C:\Users\Zephyrus G14\AppData\Local\Programs\OpenAI\Codex\bin\codex.exe"
if (!(Test-Path -LiteralPath $codexPath -PathType Leaf)) { throw "Codex CLI를 찾을 수 없습니다: $codexPath" }

$qaExtractor = "C:\AI\scripts\extract_ppt_for_qa.ps1"
if (!(Test-Path -LiteralPath $qaExtractor -PathType Leaf)) { throw "PPT QA 전용 추출기를 찾을 수 없습니다: $qaExtractor" }

$tempDir   = "C:\AI\work\temp"
$outputDir = "C:\AI\work\output"
New-Item -ItemType Directory -Path $tempDir -Force | Out-Null
New-Item -ItemType Directory -Path $outputDir -Force | Out-Null

$baseName = [System.IO.Path]::GetFileNameWithoutExtension($FilePath)
$stamp    = Get-Date -Format "yyyyMMdd_HHmmss"

$fullExtractPath   = Join-Path $tempDir "codex_qa_v3_full_${stamp}.json"
$compactSourcePath = Join-Path $tempDir "codex_qa_v3_source_${stamp}.txt"
$rawPath           = Join-Path $tempDir "codex_qa_v3_raw_${stamp}.txt"
$stderrPath        = Join-Path $tempDir "codex_qa_v3_stderr_${stamp}.txt"
$qaPath            = Join-Path $outputDir "${baseName}_QA_v3_${stamp}.json"

& $qaExtractor -FilePath $FilePath -OutputPath $fullExtractPath

if (!(Test-Path -LiteralPath $fullExtractPath -PathType Leaf)) { throw "PPT QA 전용 추출에 실패했습니다." }

$full = Get-Content -LiteralPath $fullExtractPath -Raw -Encoding UTF8 | ConvertFrom-Json

$coverageLines = @(
    "standard_text=" + [string]$full.coverage.standard_text,
    "tables=" + [string]$full.coverage.tables,
    "grouped_shapes=" + [string]$full.coverage.grouped_shapes,
    "smartart=" + [string]$full.coverage.smartart,
    "chart_titles_axes_series_labels=" + [string]$full.coverage.chart_titles_axes_series_labels,
    "notes=" + [string]$full.coverage.notes,
    "alternative_text=" + [string]$full.coverage.alternative_text,
    "rendered_visual_layout=" + [string]$full.coverage.rendered_visual_layout
)

$compact = @"
[PPT QA SOURCE]
Source: $FilePath
Slides: $($full.slide_count)

[COVERAGE]
$($coverageLines -join "`r`n")

[CONTENT]
$($full.all_qa_text)
"@

$utf8Bom = New-Object System.Text.UTF8Encoding($true)
[System.IO.File]::WriteAllText($compactSourcePath, $compact, $utf8Bom)

$instruction = @"
You are the final CONTENT QA gate for Jungle.

ORIGINAL ARTIFACT PATH (metadata only; DO NOT open it):
$FilePath

THE ONLY CONTENT SOURCE YOU MAY READ:
$compactSourcePath

ORIGINAL USER REQUEST:
$UserRequest

IMPORTANT:
- The QA source was generated by a PPT-specific extractor.
- It includes standard text, table cell text, grouped-shape text, SmartArt text, chart titles/axes/series/data labels when available, notes, and alternative text.
- If a fact such as FTE, ROI, major tasks, expected effects, or measurement criteria appears anywhere in the supplied source, treat it as PRESENT.
- Do not claim content is missing when it is visibly present in a table or other extracted structure.
- If information is only partially supported, describe exactly what is missing instead of saying the whole topic is absent.

STRICT SCOPE:
- Read ONLY $compactSourcePath.
- DO NOT open/unzip/inspect/render the original PPT/PPTX.
- DO NOT inspect package XML.
- DO NOT use web search, connectors, Google Drive, or external knowledge.
- Do not modify files.
- This pass is CONTENT QA only.
- Visual overlap, clipping, spacing, image quality, and rendered layout are out of scope.
- Report at most 12 issues.
- Do not output chain-of-thought or internal reasoning.

MANDATORY SKILLS:
1. Apply the installed Codex skill "ax-deliverables".
2. Then apply the installed Codex skill "humanizer-kr".
3. If either is unavailable, mark it MISSING.

CHECK:
- logical gaps / unsupported jumps
- duplicated messages
- inconsistent terminology, numbers, dates, labels, units
- executive readability and decision-usefulness
- grounding in supplied source
- awkward or formulaic AI-style Korean
- excessive slogans/filler/repetition
- unnatural noun stacking / translation-like Korean
- unclear subject, responsibility, action, or decision
- residual template/source text leakage visible in extracted content
- whether quantitative effects include enough definition/basis to be interpretable

Return ONLY one valid JSON object.

{
  "overall_status": "PASS | REVISE | FAIL",
  "executive_readiness_score": 0,
  "review_scope": "content_only_full_ppt_extract",
  "visual_review_status": "NOT_PERFORMED",
  "skills": {
    "ax-deliverables": {"status": "USED | MISSING", "note": ""},
    "humanizer-kr": {"status": "USED | MISSING", "note": ""}
  },
  "issue_counts": {"critical": 0, "major": 0, "minor": 0},
  "issues": [
    {
      "severity": "critical | major | minor",
      "category": "logic | duplication | consistency | grounding | executive_readability | humanizer | template_leak | other",
      "location": "slide/page/section",
      "current_text": "short excerpt when useful",
      "problem": "concise explanation",
      "recommendation": "specific revision direction"
    }
  ],
  "humanizer_summary": {"ai_style_risk": "low | medium | high", "patterns": []},
  "revision_required": true,
  "final_summary": "2-4 concise Korean sentences"
}

SCORING:
- 90-100: ready for executive delivery with at most minor polish
- 80-89: good but should be revised before important delivery
- 70-79: substantial revision needed
- below 70: not delivery-ready

STATUS:
- PASS: no critical/major issues and score >= 90
- REVISE: fixable major/minor issues exist
- FAIL: critical factual/logical/template-leak problems make delivery unsafe
"@

$psi = New-Object System.Diagnostics.ProcessStartInfo
$psi.FileName = $codexPath
$psi.Arguments = "exec --skip-git-repo-check --sandbox read-only --config model_reasoning_effort=$Reasoning -"
$psi.UseShellExecute = $false
$psi.RedirectStandardInput = $true
$psi.RedirectStandardOutput = $true
$psi.RedirectStandardError = $true
$psi.CreateNoWindow = $true

try {
    $psi.StandardOutputEncoding = New-Object System.Text.UTF8Encoding($false)
    $psi.StandardErrorEncoding  = New-Object System.Text.UTF8Encoding($false)
} catch {}

$proc = New-Object System.Diagnostics.Process
$proc.StartInfo = $psi

Write-Host ""
Write-Host "========================================"
Write-Host " JUNGLE CODEX QA GATE v3"
Write-Host "========================================"
Write-Host ""
Write-Host "Scope     : CONTENT ONLY / FULL PPT EXTRACT"
Write-Host "Source    :" $compactSourcePath
Write-Host "Reasoning :" $Reasoning
Write-Host ""
Write-Host "Codex QA started..."

[void]$proc.Start()

$stdoutTask = $proc.StandardOutput.ReadToEndAsync()
$stderrTask = $proc.StandardError.ReadToEndAsync()

$utf8 = New-Object System.Text.UTF8Encoding($false)
$bytes = $utf8.GetBytes($instruction)
$proc.StandardInput.BaseStream.Write($bytes, 0, $bytes.Length)
$proc.StandardInput.BaseStream.Flush()
$proc.StandardInput.Close()

$started = Get-Date
$nextProgress = 15

while (-not $proc.HasExited) {
    Start-Sleep -Seconds 1
    $elapsed = [int]((Get-Date) - $started).TotalSeconds
    if ($elapsed -ge $nextProgress) {
        Write-Host ("Codex QA running... {0}s" -f $elapsed)
        $nextProgress += 15
    }
}

$proc.WaitForExit()

$rawText = $stdoutTask.Result
$stderrText = $stderrTask.Result

[System.IO.File]::WriteAllText($rawPath, $rawText, $utf8Bom)
[System.IO.File]::WriteAllText($stderrPath, $stderrText, $utf8Bom)

if ($proc.ExitCode -ne 0) { throw "Codex QA 실행 실패 (exit=$($proc.ExitCode)). stderr: $stderrPath" }
if ([string]::IsNullOrWhiteSpace($rawText)) { throw "Codex QA 응답이 비어 있습니다." }

$firstBrace = $rawText.IndexOf("{")
$lastBrace  = $rawText.LastIndexOf("}")
if ($firstBrace -lt 0 -or $lastBrace -le $firstBrace) { throw "Codex QA 응답에서 JSON을 찾지 못했습니다. Raw: $rawPath" }

$jsonText = $rawText.Substring($firstBrace, $lastBrace - $firstBrace + 1)

try { $qa = $jsonText | ConvertFrom-Json }
catch { throw "Codex QA JSON 파싱 실패. Raw: $rawPath" }

$jsonPretty = $qa | ConvertTo-Json -Depth 12
[System.IO.File]::WriteAllText($qaPath, $jsonPretty, $utf8Bom)

$critical = 0
$major = 0
$minor = 0
try { $critical = [int]$qa.issue_counts.critical } catch {}
try { $major = [int]$qa.issue_counts.major } catch {}
try { $minor = [int]$qa.issue_counts.minor } catch {}

$axStatus = "UNKNOWN"
$humanizerStatus = "UNKNOWN"
try { $axStatus = [string]$qa.skills.'ax-deliverables'.status } catch {}
try { $humanizerStatus = [string]$qa.skills.'humanizer-kr'.status } catch {}

$elapsedTotal = [int]((Get-Date) - $started).TotalSeconds

Write-Host ""
Write-Host "========================================"
Write-Host " JUNGLE CODEX QA RESULT v3"
Write-Host "========================================"
Write-Host ""
Write-Host "Status     :" $qa.overall_status
Write-Host "Score      :" $qa.executive_readiness_score
Write-Host "Critical   :" $critical
Write-Host "Major      :" $major
Write-Host "Minor      :" $minor
Write-Host "AX Skill   :" $axStatus
Write-Host "Humanizer  :" $humanizerStatus
Write-Host "Scope      :" $qa.review_scope
Write-Host "Elapsed    :" $elapsedTotal "sec"
Write-Host "QA File    :" $qaPath
Write-Host ""
Write-Host "Summary:"
Write-Host $qa.final_summary
Write-Host ""
Write-Host "STATUS: CODEX_QA_GATE_V3_COMPLETE"
